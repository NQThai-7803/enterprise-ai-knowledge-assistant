"""The text-only Ollama model build: Modelfile rewrite and manifest lookup, without Ollama."""

from __future__ import annotations

from pathlib import Path

import pytest

from scripts.deploy import ollama_text_model as tool

MODELFILE = """# Modelfile generated by "ollama show"
FROM /models/blobs/sha256-aaa
FROM /models/blobs/sha256-ppp
RENDERER qwen3.5
PARAMETER temperature 1
PARAMETER num_gpu 10
"""


def test_projector_from_line_goes_and_num_gpu_is_set_once() -> None:
    text = tool.text_modelfile(MODELFILE, ["sha256-ppp"], 99)
    assert "sha256-ppp" not in text
    assert "FROM /models/blobs/sha256-aaa" in text
    assert text.count("num_gpu") == 1 and text.rstrip().endswith("PARAMETER num_gpu 99")
    assert "RENDERER qwen3.5" in text and "PARAMETER temperature 1" in text


def test_without_num_gpu_the_base_parameters_stay() -> None:
    assert "PARAMETER num_gpu 10" in tool.text_modelfile(MODELFILE, ["sha256-ppp"], None)


def test_a_base_without_projector_or_with_two_models_is_refused() -> None:
    with pytest.raises(ValueError, match="no projector"):
        tool.text_modelfile(MODELFILE, [], 99)
    with pytest.raises(ValueError, match="exactly one FROM"):
        tool.text_modelfile(MODELFILE, ["sha256-zzz"], 99)


def test_manifest_and_layers() -> None:
    root = Path("/m")
    assert tool.manifest_path(root, "qwen3.5:4b") == Path(
        "/m/manifests/registry.ollama.ai/library/qwen3.5/4b"
    )
    assert tool.manifest_path(root, "user/model").parts[-3:] == ("user", "model", "latest")
    manifest = {
        "layers": [
            {"mediaType": "application/vnd.ollama.image.model", "digest": "sha256:aaa"},
            {"mediaType": "application/vnd.ollama.image.projector", "digest": "sha256:ppp"},
        ]
    }
    assert tool.projector_digests(manifest) == ["sha256-ppp"]
    assert tool.has_vision("  Capabilities\n    completion\n    vision\n")
    assert not tool.has_vision("  Capabilities\n    completion\n    tools\n")
